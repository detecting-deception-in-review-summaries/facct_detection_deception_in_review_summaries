"""Print the LaTeX table of how much text the modifications change, by aspect count.

For factual errors and quantifier swaps, the share of the parent summary's
words that changed; for aspect deletions, how much shorter the summary became. Both are
read from fields stored on every modification in `data/summaries.jsonl`:

  changed_word_percentage  100 * (1 - word-level SequenceMatcher ratio between
                           parent and modified summary)
  length_reduction         (parent words - modified words) / parent words,
                           printed here as a percentage

Only modifications by the primary modifier count (the hand-written edits are
excluded), with both directions (advantageous and disadvantageous) pooled at
each aspect count, since the table describes the edits the study scores.

The table is printed and written to results/tables/modification_percentages.tex.

Usage:
    uv run python modification_validation/print_modifications_percentages.py
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parent.parent
SUMMARIES_PATH = PROJECT_ROOT / "data/summaries.jsonl"
OUTPUT_PATH = PROJECT_ROOT / "results/tables/modification_percentages.tex"

# (family, column title, field, scale to percent)
COLUMNS = [
    ("factual_error", "Factual Error", "changed_word_percentage", 1.0),
    ("aspect_deletion", "Aspect Deletion", "length_reduction", 100.0),
    ("quantifier_swap", "Quantifier Swap", "changed_word_percentage", 1.0),
]
GENERATOR = "primary_llm"


def load_modifications(path: Path) -> pd.DataFrame:
    """The modifications in `summaries.jsonl`: rows that are not their own parent."""
    records = pd.read_json(path, lines=True)
    return records.loc[records["record_id"] != records["parent_summary_id"]]


def modification_percentages_table(modifications: pd.DataFrame) -> pd.DataFrame:
    """Mean, SD and count per (family, aspect count), in percent."""
    tables = []
    for family, _, field, scale in COLUMNS:
        edits = modifications.loc[modifications["family"] == family]
        stats = (edits[field] * scale).groupby(edits["severity"]).agg(["count", "mean", "std"])
        tables.append(stats.rename(columns={"count": "n", "std": "sd"}).assign(family=family))
    table = pd.concat(tables).reset_index()
    table["severity"] = table["severity"].astype(int)
    return table.set_index(["severity", "family"]).sort_index()


def latex(table: pd.DataFrame) -> str:
    def cells(severity: int, family: str) -> str:
        if (severity, family) not in table.index:
            return "-- & --"
        row = table.loc[(severity, family)]
        return f"{row['mean']:.1f} & {row['sd']:.1f}"

    body = [
        f"{severity} & " + " & ".join(cells(severity, family) for family, *_ in COLUMNS) + r" \\"
        for severity in sorted(table.index.get_level_values("severity").unique())
    ]
    headers = " & ".join(rf"\multicolumn{{2}}{{c}}{{\textbf{{{title}}}}}" for _, title, *_ in COLUMNS)
    return "\n".join([
        r"\begin{table}[h!]",
        r"\centering",
        r"\caption{Modifications introduced by the insertion of factual errors, "
        r"aspect deletions, and quantifier swaps. For factual errors and quantifier swaps, "
        r"the percentage of changed words is shown, whereas for aspect deletions, the percentage "
        r"reduction in summary length is shown. For each, we report standard deviations (SD).}",
        r"\label{tab:modification_percentages}",
        r"\begin{tabular}{l" + "rr" * len(COLUMNS) + "}",
        r"\toprule",
        f" & {headers} \\\\",
        r"\textbf{Nr. Aspects} & " + " & ".join([r"Mean (\%) & SD"] * len(COLUMNS)) + r" \\",
        r"\midrule",
        *body,
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{table}",
    ])


def main() -> None:
    modifications = load_modifications(SUMMARIES_PATH)
    modifications = modifications.loc[
        modifications["generator"].eq(GENERATOR)
        & modifications["family"].isin([family for family, *_ in COLUMNS])
    ]
    if modifications.empty:
        raise SystemExit(f"No {GENERATOR} modifications of these families in {SUMMARIES_PATH}.")

    table = modification_percentages_table(modifications)
    output = "\n".join([
        f"% Generated by modification_validation/print_modifications_percentages.py from {SUMMARIES_PATH.name}",
        "% Edits per cell: " + "; ".join(
            f"{family} x{severity}: {int(row['n'])}" for (severity, family), row in table.iterrows()),
        latex(table),
    ])
    print(output)

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(output + "\n", encoding="utf-8")
    print(f"\nSaved: {OUTPUT_PATH.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
